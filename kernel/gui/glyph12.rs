#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_cover_ascii_visible() {
        for c in 'A'..='Z' {
            assert!(glyph(c).iter().any(|r| *r != 0), "字模为空 {}", c);
        }
        for c in '0'..='9' {
            assert!(glyph(c).iter().any(|r| *r != 0), "字模为空 {}", c);
        }
        assert!(glyph(' ').iter().all(|r| *r == 0));
    }

    #[test]
    fn unknown_char_falls_back() {
        assert_eq!(glyph('中'), glyph('?'));
    }
}
