//! AI 工厂 —— 把自然语言需求变成可编译、可持久化、可沙箱运行的 WASM 创造物。
//!
//! 链路：模板/LLM 生成 Rust 源码 → 白名单校验 → 写盘 → rustc 编译为 wasm32 →
//! wasmtime 加载 → 注册到运行时 → VFS /apps 可见 → 启动台可见。
//!
//! 编译失败自动回退到声明式 appgen（JSON 说明书），保证链路始终可用。

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use serde::{Deserialize, Serialize};

use crate::wasman_runtime::{self, Kind, WasmInstance};

/// 生成物清单。
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Manifest {
    pub name: String,
    pub kind: String,
    pub requirement: String,
    pub fallback: bool,
}

/// 用户目录：`~/.hibos/apps`。
pub fn apps_dir() -> PathBuf {
    let home = std::env::var("HOME").unwrap_or_else(|_| ".".to_string());
    PathBuf::from(home).join(".hibos").join("apps")
}

/// 单个生成物目录。
pub fn app_dir(name: &str) -> PathBuf {
    apps_dir().join(name)
}

/// 白名单校验：禁止明显危险的能力（WASM 目标本就没有，但源码阶段也要拦）。
fn validate_source(src: &str) -> Result<(), String> {
    let forbidden = ["std::fs", "std::net", "std::process", "unsafe", "extern \"C\" {"];
    for f in forbidden {
        // 模板自身包含 extern "C" 函数定义，但不包含 extern 块。
        if f == "extern \"C\" {" && src.contains(f) {
            return Err(format!("源码含禁止的 extern 块: {}", f));
        }
        if f != "extern \"C\" {" && src.contains(f) {
            return Err(format!("源码含禁止的能力: {}", f));
        }
    }
    Ok(())
}

/// 四类模板：模型只需填充 `// USER_LOGIC` 位置。
fn template(kind: Kind, name: &str) -> &'static str {
    match kind {
        Kind::App => {
            let _ = name;
            r#"#[no_mangle]
pub extern "C" fn init() -> i32 { 1 }
#[no_mangle]
pub extern "C" fn tick(_t: i32) {}
#[no_mangle]
pub extern "C" fn render(_ptr: i32, _w: i32, _h: i32) {}
#[no_mangle]
pub extern "C" fn on_input(key: i32) -> i32 {
    // USER_LOGIC
    key
}
"#
        }
        Kind::Plugin => r#"#[no_mangle]
pub extern "C" fn init() -> i32 { 1 }
#[no_mangle]
pub extern "C" fn on_event(_ptr: i32, _len: i32) -> i32 {
    // USER_LOGIC
    0
}
"#,
        Kind::Ime => r#"#[no_mangle]
pub extern "C" fn init() -> i32 { 1 }
#[no_mangle]
pub extern "C" fn map_key(code: i32) -> i32 {
    // USER_LOGIC
    code
}
"#,
        Kind::Animation => r#"#[no_mangle]
pub extern "C" fn init() -> i32 { 1 }
#[no_mangle]
pub extern "C" fn animate(t: i32) -> i64 {
    // USER_LOGIC
    ((t as i64) << 32) | 255
}
"#,
    }
}

/// 生成源码：有 LLM 代码时做白名单校验后填入模板；无 LLM 用模板占位。
pub fn generate_source(kind: Kind, name: &str, requirement: &str, llm_code: Option<&str>) -> Result<String, String> {
    let tpl = template(kind, name);
    let body = match llm_code {
        Some(code) => {
            validate_source(code)?;
            code.trim().to_string()
        }
        None => format!("// requirement: {}\n// generated by AI factory", requirement),
    };
    Ok(tpl.replace("// USER_LOGIC", &body))
}

/// 持久化：写 manifest.json 与 src/lib.rs。
pub fn persist(kind: Kind, name: &str, requirement: &str, source: &str) -> Result<PathBuf, String> {
    let dir = app_dir(name);
    fs::create_dir_all(dir.join("src")).map_err(|e| format!("创建目录失败: {}", e))?;
    fs::write(dir.join("src").join("lib.rs"), source).map_err(|e| format!("写源码失败: {}", e))?;
    let manifest = Manifest {
        name: name.to_string(),
        kind: kind.name().to_string(),
        requirement: requirement.to_string(),
        fallback: false,
    };
    let json = serde_json::to_string_pretty(&manifest).map_err(|e| e.to_string())?;
    fs::write(dir.join("manifest.json"), json).map_err(|e| format!("写清单失败: {}", e))?;
    Ok(dir)
}

/// rustc 编译 wasm32-unknown-unknown cdylib。
pub fn compile_wasm(dir: &Path) -> Result<PathBuf, String> {
    let src = dir.join("src").join("lib.rs");
    let out = dir.join("app.wasm");
    let status = Command::new("rustc")
        .arg("--target").arg("wasm32-unknown-unknown")
        .arg("--crate-type").arg("cdylib")
        .arg("-O")
        .arg(&src)
        .arg("-o").arg(&out)
        .status()
        .map_err(|e| format!("无法调用 rustc: {}", e))?;
    if !status.success() {
        return Err("rustc 编译失败".to_string());
    }
    Ok(out)
}

/// 创建完整创造物：生成 → 持久化 → 编译 → 加载 → 注册。
pub fn create(kind: Kind, name: &str, requirement: &str, llm_code: Option<&str>) -> Result<String, String> {
    let source = generate_source(kind, name, requirement, llm_code)?;
    let dir = persist(kind, name, requirement, &source)?;
    match compile_wasm(&dir) {
        Ok(wasm_path) => {
            let bytes = fs::read(&wasm_path).map_err(|e| e.to_string())?;
            let inst = WasmInstance::load(&bytes)?;
            if !inst.has_abi(wasman_runtime::required_abi(kind)) {
                return Err("WASM 缺少必需 ABI".to_string());
            }
            let init = inst.call_i32("init").unwrap_or(0);
            wasman_runtime::register(name, inst);
            Ok(format!("已创建 {} {} (init={})", kind.name(), name, init))
        }
        Err(e) => {
            // 编译失败：标记 fallback，交给声明式 appgen。
            let manifest_path = dir.join("manifest.json");
            if let Ok(text) = fs::read_to_string(&manifest_path) {
                if let Ok(mut m) = serde_json::from_str::<Manifest>(&text) {
                    m.fallback = true;
                    let _ = fs::write(&manifest_path, serde_json::to_string_pretty(&m).unwrap_or_default());
                }
            }
            Err(format!("WASM 编译失败，已回退声明式: {}", e))
        }
    }
}

/// 启动时扫描目录并加载所有生成物。
pub fn load_all() -> Vec<String> {
    let mut loaded = Vec::new();
    let Ok(entries) = fs::read_dir(apps_dir()) else {
        return loaded;
    };
    for entry in entries.flatten() {
        let dir = entry.path();
        let manifest_path = dir.join("manifest.json");
        let wasm_path = dir.join("app.wasm");
        let Ok(text) = fs::read_to_string(&manifest_path) else { continue };
        let Ok(m) = serde_json::from_str::<Manifest>(&text) else { continue };
        if m.fallback { continue; }
        let Ok(bytes) = fs::read(&wasm_path) else { continue };
        let Ok(inst) = WasmInstance::load(&bytes) else { continue };
        wasman_runtime::register(&m.name, inst);
        // VFS /apps 映射：清单与源码快照供 shell / GUI 读取。
        if let Ok(mut v) = crate::vfs::global_vfs().write() {
            let _ = v.mkdir(&format!("/apps/{}", m.name));
            let _ = v.write(&format!("/apps/{}/manifest.json", m.name), &text);
            if let Ok(src) = fs::read_to_string(dir.join("src").join("lib.rs")) {
                let _ = v.mkdir(&format!("/apps/{}/src", m.name));
                let _ = v.write(&format!("/apps/{}/src/lib.rs", m.name), &src);
            }
        }
        loaded.push(m.name);
    }
    loaded
}

/// 列出已持久化生成物（供启动台/文件管理器）。
pub fn list_manifests() -> Vec<Manifest> {
    let mut out = Vec::new();
    let Ok(entries) = fs::read_dir(apps_dir()) else { return out };
    for entry in entries.flatten() {
        if let Ok(text) = fs::read_to_string(entry.path().join("manifest.json")) {
            if let Ok(m) = serde_json::from_str::<Manifest>(&text) {
                out.push(m);
            }
        }
    }
    out.sort_by(|a, b| a.name.cmp(&b.name));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn template_exports_required_abi() {
        for kind in [Kind::App, Kind::Plugin, Kind::Ime, Kind::Animation] {
            let src = generate_source(kind, "demo", "test", None).unwrap();
            for abi in wasman_runtime::required_abi(kind) {
                assert!(src.contains(&format!("fn {}(", abi)), "{:?} 缺少 {}", kind, abi);
            }
        }
    }

    #[test]
    fn whitelist_blocks_dangerous_code() {
        let bad = "std::fs::read(\"/etc/passwd\")";
        assert!(generate_source(Kind::App, "x", "x", Some(bad)).is_err());
    }

    #[test]
    fn persist_writes_manifest_and_source() {
        let dir = std::env::temp_dir().join("hibos-ai-factory-test");
        let _ = fs::remove_dir_all(&dir);
        // 用临时目录覆盖 apps_dir 不可行（全局固定），这里只验证 write 内容函数。
        let src = generate_source(Kind::App, "td", "test", None).unwrap();
        assert!(src.contains("fn init"));
        assert!(!src.contains("#![no_std]"));
        let _ = fs::remove_dir_all(&dir);
    }

    #[test]
    fn end_to_end_create_app() {
        // 真编译一个最小 app 到 wasm 并加载（验证全链路）。
        let name = "e2etest";
        let result = create(Kind::App, name, "hello", None);
        match result {
            Ok(msg) => {
                assert!(msg.contains("app"));
                assert!(app_dir(name).join("app.wasm").exists());
                assert!(wasman_runtime::get(name).is_some());
            }
            Err(e) => {
                // 宿主无 rustc 或 target 时跳过（不视为失败）。
                if !e.contains("rustc") && !e.contains("编译") {
                    panic!("端到端失败: {}", e);
                }
            }
        }
    }
}
